-- Enable pgcrypto for UUID generation if not already enabled
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- -------------------------------------------------------------
-- 1. Create the Batches / Reactions Metadata Table
-- -------------------------------------------------------------
CREATE TABLE IF NOT EXISTS bioprocess_batches (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    batch_name TEXT NOT NULL,
    scientist_name TEXT NOT NULL,
    organism TEXT DEFAULT 'Saccharomyces cerevisiae',
    broth_type TEXT DEFAULT 'YPD Nutrient Broth',
    notes TEXT,
    status TEXT DEFAULT 'active' CHECK (status IN ('active', 'completed', 'aborted')),
    started_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    harvest_recommended_at TIMESTAMPTZ,
    stopped_at TIMESTAMPTZ,
    harvest_delay_minutes DOUBLE PRECISION,
    peak_turbidity DOUBLE PRECISION DEFAULT 0.0,
    peak_gas DOUBLE PRECISION DEFAULT 0.0
);

-- -------------------------------------------------------------
-- 2. Create the Telemetry Readings Table (Linked to Batches)
-- -------------------------------------------------------------
CREATE TABLE IF NOT EXISTS bioprocess_readings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    batch_id UUID REFERENCES bioprocess_batches(id) ON DELETE CASCADE,
    device_id TEXT DEFAULT 'ESP32_BIO_01',
    turbidity DOUBLE PRECISION NOT NULL,     -- In NTU / Optical Density (OD)
    temperature DOUBLE PRECISION NOT NULL,   -- In degrees Celsius (°C)
    ph DOUBLE PRECISION NOT NULL,            -- pH scale (0.0 to 14.0)
    gas DOUBLE PRECISION DEFAULT 400.0,      -- Headspace CO2 / VOC (in PPM)
    detected_phase TEXT DEFAULT 'log'        -- Lag, Log, Stationary, Death
);

-- Safe migration columns in case table previously existed
ALTER TABLE bioprocess_readings ADD COLUMN IF NOT EXISTS batch_id UUID REFERENCES bioprocess_batches(id) ON DELETE CASCADE;
ALTER TABLE bioprocess_readings ADD COLUMN IF NOT EXISTS gas DOUBLE PRECISION DEFAULT 400.0;
ALTER TABLE bioprocess_readings ADD COLUMN IF NOT EXISTS detected_phase TEXT DEFAULT 'log';

-- -------------------------------------------------------------
-- 3. Indexes for High-Speed Time-Series Queries
-- -------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_bioprocess_readings_created_at 
ON bioprocess_readings (created_at DESC);

CREATE INDEX IF NOT EXISTS idx_bioprocess_readings_batch_id 
ON bioprocess_readings (batch_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_bioprocess_batches_status 
ON bioprocess_batches (status);

-- -------------------------------------------------------------
-- 4. Enable Row Level Security (RLS) & Policies
-- -------------------------------------------------------------
ALTER TABLE bioprocess_batches ENABLE ROW LEVEL SECURITY;
ALTER TABLE bioprocess_readings ENABLE ROW LEVEL SECURITY;

-- Batches policies
CREATE POLICY "Allow public read access on batches" 
ON bioprocess_batches FOR SELECT USING (true);

CREATE POLICY "Allow public insert on batches" 
ON bioprocess_batches FOR INSERT WITH CHECK (true);

CREATE POLICY "Allow public update on batches" 
ON bioprocess_batches FOR UPDATE USING (true);

-- Readings policies
CREATE POLICY "Allow public read access on readings" 
ON bioprocess_readings FOR SELECT USING (true);

CREATE POLICY "Allow public insert on readings" 
ON bioprocess_readings FOR INSERT WITH CHECK (true);

